from urllib.parse import parse_qs, unquote, urlsplit

import pg8000

from . import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS Users (
 id TEXT PRIMARY KEY, username TEXT NOT NULL,
 email TEXT NOT NULL, display_name TEXT NOT NULL,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('Admin','Hotel Personnel','Parking Personnel','User')),
 active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci_idx ON Users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci_idx ON Users (lower(email));
CREATE TABLE IF NOT EXISTS Personnel (
 user_id TEXT PRIMARY KEY REFERENCES Users(id) ON DELETE CASCADE,
 department TEXT NOT NULL CHECK(department IN ('Hotel','Parking')),
 active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS Rooms (
 id TEXT PRIMARY KEY, room_number TEXT NOT NULL UNIQUE, room_type TEXT NOT NULL DEFAULT 'Standard',
 status TEXT NOT NULL DEFAULT 'Available' CHECK(status IN ('Available','Reserved','Occupied','Maintenance')),
 notes TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS ParkingSlots (
 id TEXT PRIMARY KEY, slot_code TEXT NOT NULL UNIQUE, accessible INTEGER NOT NULL DEFAULT 0,
 ev_charging INTEGER NOT NULL DEFAULT 0,
 status TEXT NOT NULL DEFAULT 'Available' CHECK(status IN ('Available','Reserved','Occupied','Maintenance'))
);
CREATE TABLE IF NOT EXISTS Vehicles (
 id TEXT PRIMARY KEY, owner_user_id TEXT NOT NULL REFERENCES Users(id), vehicle_type TEXT NOT NULL,
 plate_number TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS vehicles_plate_number_ci_idx ON Vehicles (lower(plate_number));
CREATE TABLE IF NOT EXISTS HotelBookings (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES Users(id), assigned_personnel_id TEXT REFERENCES Users(id),
 room_id TEXT REFERENCES Rooms(id), property_name TEXT NOT NULL DEFAULT '', guest_name TEXT NOT NULL,
 guest_email TEXT NOT NULL, guest_phone TEXT NOT NULL DEFAULT '', room_type TEXT NOT NULL,
 check_in TEXT NOT NULL, check_out TEXT NOT NULL, guest_count INTEGER NOT NULL CHECK(guest_count > 0),
 status TEXT NOT NULL DEFAULT 'Pending', notes TEXT NOT NULL DEFAULT '', internal_notes TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_HotelBookings_Dates ON HotelBookings(check_in, check_out, status);
CREATE TABLE IF NOT EXISTS ParkingBookings (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES Users(id), assigned_personnel_id TEXT REFERENCES Users(id),
 parking_slot_id TEXT REFERENCES ParkingSlots(id), vehicle_id TEXT NOT NULL REFERENCES Vehicles(id),
 property_name TEXT NOT NULL DEFAULT '', start_at TEXT NOT NULL, end_at TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Pending', notes TEXT NOT NULL DEFAULT '', internal_notes TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_ParkingBookings_Times ON ParkingBookings(start_at, end_at, status);
CREATE TABLE IF NOT EXISTS Notifications (
 id TEXT PRIMARY KEY, recipient_user_id TEXT REFERENCES Users(id) ON DELETE CASCADE, audience_role TEXT,
 category TEXT NOT NULL, booking_type TEXT, booking_id TEXT, title TEXT NOT NULL, message TEXT NOT NULL,
 created_at TEXT NOT NULL, read_at TEXT
);
CREATE TABLE IF NOT EXISTS BookingHistory (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_type TEXT NOT NULL, booking_id TEXT NOT NULL,
 actor_user_id TEXT REFERENCES Users(id), action TEXT NOT NULL, old_status TEXT, new_status TEXT,
 details TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS IX_BookingHistory_Booking ON BookingHistory(booking_type, booking_id, created_at);
CREATE TABLE IF NOT EXISTS Sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES Users(id) ON DELETE CASCADE,
 expires_at TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
"""


class DatabaseCursor:
    def __init__(self, cursor: Any) -> None:
        self._cursor = cursor

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    def fetchone(self) -> dict[str, Any] | None:
        row = self._cursor.fetchone()
        if row is None:
            return None
        return dict(zip((column[0] for column in self._cursor.description), row))

    def fetchall(self) -> list[dict[str, Any]]:
        columns = [column[0] for column in self._cursor.description]
        return [dict(zip(columns, row)) for row in self._cursor.fetchall()]


class DatabaseConnection:
    def __init__(self, connection: Any) -> None:
        self._connection = connection

    def execute(self, query: str, params: Iterable[Any] = ()) -> DatabaseCursor:
        cursor = self._connection.cursor()
        cursor.execute(query.replace("?", "%s"), tuple(params))
        return DatabaseCursor(cursor)

    def executemany(self, query: str, params: Iterable[Iterable[Any]]) -> DatabaseCursor:
        cursor = self._connection.cursor()
        cursor.executemany(query.replace("?", "%s"), params)
        return DatabaseCursor(cursor)

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def __enter__(self) -> DatabaseConnection:
        return self

    def __exit__(self, exc_type: object, exc_value: object, traceback: object) -> bool | None:
        try:
            if exc_type is None:
                self._connection.commit()
            else:
                self._connection.rollback()
        finally:
            self._connection.close()
        return None

    def close(self) -> None:
        self._connection.close()


def connect() -> DatabaseConnection:
    if not config.SUPABASE_DATABASE_URL:
        raise RuntimeError("Set SUPABASE_DATABASE_URL to your Supabase PostgreSQL connection string.")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{0,62}", config.SUPABASE_DATABASE_SCHEMA):
        raise RuntimeError("SUPABASE_DATABASE_SCHEMA must be a valid PostgreSQL schema name.")
    parsed = urlsplit(config.SUPABASE_DATABASE_URL)
    if parsed.scheme not in {"postgres", "postgresql"} or not parsed.hostname or not parsed.path.strip("/"):
        raise RuntimeError("SUPABASE_DATABASE_URL must be a valid PostgreSQL connection URL.")
    options = parse_qs(parsed.query)
    sslmode = options.get("sslmode", ["require"])[0]
    if sslmode != "disable" and sslmode not in {"require", "verify-ca", "verify-full", "prefer"}:
        raise RuntimeError("SUPABASE_DATABASE_URL has an unsupported sslmode.")
    connection = pg8000.dbapi.connect(
        user=unquote(parsed.username or ""),
        password=unquote(parsed.password or ""),
        host=parsed.hostname,
        port=parsed.port or 5432,
        database=unquote(parsed.path.lstrip("/")),
        ssl_context=ssl.create_default_context() if sslmode != "disable" else None,
    )
    if config.SUPABASE_DATABASE_SCHEMA != "public":
        cursor = connection.cursor()
        cursor.execute(f'SET search_path TO "{config.SUPABASE_DATABASE_SCHEMA}"')
    return DatabaseConnection(connection)


def initialize() -> None:
    with connect() as connection:
        connection.executescript(SCHEMA)
        if not connection.execute("SELECT COUNT(*) AS count FROM Rooms").fetchone()["count"]:
            connection.executemany(
                "INSERT INTO Rooms(id,room_number,room_type) VALUES(?,?,?)",
                [(str(uuid.uuid4()), str(101 + i), "Deluxe" if i % 6 == 5 else "Standard") for i in range(36)],
            )
        if not connection.execute("SELECT COUNT(*) AS count FROM ParkingSlots").fetchone()["count"]:
            connection.executemany(
                "INSERT INTO ParkingSlots(id,slot_code,accessible,ev_charging) VALUES(?,?,?,?)",
                [(str(uuid.uuid4()), f"P-{i:02}", int(i <= 4), int(i % 8 == 0)) for i in range(1, 49)],
            )